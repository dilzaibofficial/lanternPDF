import { PDFDocument } from "@cantoo/pdf-lib";
import * as pdfjs from "pdfjs-dist/legacy/build/pdf.mjs";
import { describe, expect, it } from "vitest";
import { engineContext, ensureScanned } from "../../../src/lib/pdf/engine/context";
import { interpret } from "../../../src/lib/pdf/engine/interpret";
import { type TextLine, buildLines } from "../../../src/lib/pdf/engine/lines";
import { IDENTITY } from "../../../src/lib/pdf/engine/matrix";
import { pruneUnreachable } from "../../../src/lib/pdf/engine/prune";
import { readPageContent } from "../../../src/lib/pdf/engine/streams";
import { type EditOutcome, type LineEditRequest, applyTextEdits, whyNotEditable } from "../../../src/lib/pdf/engine/textEdit";
import { fixtureBytes, hasFixture } from "../../fixtures/build";

/**
 * The engine against PDFs written by other producers: Chromium's print-to-PDF (one glyph per operator), PDFKit
 * (kerned and justified TJ arrays) and pdf-lib. Fixtures are generated by `npm run fixtures`.
 */

const load = async (name: string) => PDFDocument.load(fixtureBytes(name));

function linesOf(doc: PDFDocument, pageIndex = 0): TextLine[] {
  const context = engineContext(doc);
  ensureScanned(context);
  const result = interpret(doc, readPageContent(doc, doc.getPage(pageIndex)), IDENTITY, context.fonts, {}, { formSources: context.formSources });
  return buildLines(result.runs);
}

const lineWith = (doc: PDFDocument, text: string, pageIndex = 0): TextLine => {
  const found = linesOf(doc, pageIndex).find((line) => line.text === text);
  if (!found) throw new Error(`no line “${text}”; have ${linesOf(doc, pageIndex).map((l) => `“${l.text}”`).join(", ")}`);
  return found;
};

interface Item {
  str: string;
  x: number;
  y: number;
  width: number;
}

async function pdfjsItems(bytes: Uint8Array, pageNumber = 1): Promise<Item[]> {
  const task = pdfjs.getDocument({ data: new Uint8Array(bytes), verbosity: 0 });
  const doc = await task.promise;
  try {
    const page = await doc.getPage(pageNumber);
    const content = await page.getTextContent();
    return content.items
      .filter((item) => "str" in item && item.str.trim() !== "")
      .map((item) => {
        const it = item as { str: string; transform: number[]; width: number };
        return { str: it.str, x: it.transform[4] as number, y: it.transform[5] as number, width: it.width };
      });
  } finally {
    await task.destroy();
  }
}

async function edit(doc: PDFDocument, lineText: string, request: Omit<LineEditRequest, "lineId">, pageIndex = 0) {
  const line = lineWith(doc, lineText, pageIndex);
  const report = await applyTextEdits(doc, pageIndex, [{ lineId: line.id, ...request }]);
  pruneUnreachable(doc);
  const bytes = await doc.save();
  return { outcome: report.outcomes[0] as EditOutcome, bytes, text: (await pdfjsItems(bytes, pageIndex + 1)).map((i) => i.str).join("") };
}

/** All text of a page with positions, merged per visual word, to compare before and after. */
const joined = (items: Item[]) => items.map((i) => i.str).join("");

const needsBrowser = hasFixture("chromium-article.pdf");

describe.skipIf(!needsBrowser)("Chromium print-to-PDF (one glyph per operator)", () => {
  it("reads the page as sensible lines, not 500 single letters", async () => {
    const doc = await load("chromium-article.pdf");
    const lines = linesOf(doc);
    const texts = lines.map((l) => l.text);
    expect(lines.length).toBeLessThan(60);
    expect(texts).toContain("Quarterly Report");
    expect(texts).toContain("Gadget with a long name");
    expect(texts).toContain("$129.50");
    expect(texts).toContain("Rotated margin note");
    expect(texts).toContain("Prepared by Finance — page one");
    expect(lines.find((l) => l.text === "Rotated margin note")?.rotation).toBeCloseTo(90, 1);
    for (const line of lines) expect(whyNotEditable(line), line.text).toBeNull();
  });

  it("deletes letters from a heading and keeps every other line where it was", async () => {
    const doc = await load("chromium-article.pdf");
    const before = await pdfjsItems(await doc.save());
    const { outcome, bytes } = await edit(doc, "Quarterly Report", { text: "Quarterly Repo" });
    expect(outcome).toMatchObject({ status: "applied", mode: "A", verified: true });
    const after = await pdfjsItems(bytes);
    expect(joined(after)).toContain("Quarterly Repo");
    expect(joined(after)).not.toContain("Quarterly Report");
    for (const keep of ["Overview", "Figures", "Gizmo", "$129.50"]) {
      const was = before.find((i) => i.str === keep);
      const is = after.find((i) => i.str === keep);
      expect(is, keep).toBeDefined();
      expect(is?.x).toBeCloseTo(was?.x ?? Number.NaN, 2);
      expect(is?.y).toBeCloseTo(was?.y ?? Number.NaN, 2);
    }
    // The heading starts where it started.
    const heading = after.find((i) => i.str.startsWith("Quarterly"));
    const old = before.find((i) => i.str.startsWith("Quarterly"));
    expect(heading?.x).toBeCloseTo(old?.x ?? Number.NaN, 2);
  });

  it("draws a letter the embedded subset does not have in a fallback font, in the same place", async () => {
    const doc = await load("chromium-article.pdf");
    const { outcome, bytes } = await edit(doc, "Quarterly Report", { text: "Quarterly Results" });
    // R-e-s-u-l-t-s: this heading's font subset has no "s"
    expect(outcome.status).toBe("applied");
    expect(outcome.mode).toBe("B");
    expect(outcome.fallbackChars).toContain("s");
    expect(outcome.verified).toBe(true);
    expect(joined(await pdfjsItems(bytes))).toContain("Quarterly Results");
  });

  it("changes digits in a table cell", async () => {
    const doc = await load("chromium-article.pdf");
    const { outcome, bytes } = await edit(doc, "$129.50", { text: "$130.00" });
    expect(outcome.status).toBe("applied");
    expect(joined(await pdfjsItems(bytes))).toContain("$130.00");
  });

  it("replaces a word in the middle of a sentence and moves the styled words after it along", async () => {
    const doc = await load("chromium-article.pdf");
    const full = "The company grew steadily during the year and expanded into three new markets while keeping";
    const line = lineWith(doc, full);
    // This visual line is made of five separately drawn pieces: plain, bold "three", plain, italic "keeping"…
    expect(line.segments.length).toBeGreaterThanOrEqual(4);
    const tailBefore = line.origin[0] + line.advance * line.scale;
    const bold = await pdfjsItems(await doc.save());
    const threeBefore = bold.find((i) => i.str.trim() === "three");
    const { outcome, bytes } = await edit(doc, full, { text: full.replace("steadily", "slowly") });
    expect(outcome).toMatchObject({ status: "applied", verified: true });
    const after = lineWith(doc, full.replace("steadily", "slowly"));
    expect(after.origin[0]).toBeCloseTo(line.origin[0], 2);
    // "slowly" is shorter than "steadily", so the whole line, including the bold word, ends earlier
    expect(after.origin[0] + after.advance * after.scale).toBeLessThan(tailBefore - 1);
    const threeAfter = (await pdfjsItems(bytes)).find((i) => i.str.trim() === "three");
    expect(threeAfter?.x).toBeLessThan((threeBefore?.x ?? 0) - 1);
    // and the gap before it is the one it had
    const gapBefore = (threeBefore?.x ?? 0) - line.origin[0];
    const gapAfter = (threeAfter?.x ?? 0) - after.origin[0];
    expect(gapAfter).toBeLessThan(gapBefore);
  });

  it("edits the rotated margin note along its own direction", async () => {
    const doc = await load("chromium-article.pdf");
    const line = lineWith(doc, "Rotated margin note");
    const { outcome } = await edit(doc, "Rotated margin note", { text: "Rotated margin notes" });
    expect(outcome.status).toBe("applied");
    const after = lineWith(doc, "Rotated margin notes");
    expect(after.rotation).toBeCloseTo(90, 1);
    expect(after.origin[0]).toBeCloseTo(line.origin[0], 1);
    expect(after.origin[1]).toBeCloseTo(line.origin[1], 1);
  });

  it("leaves the link, the image and the drawn table lines alone", async () => {
    const doc = await load("chromium-article.pdf");
    const beforeImages = interpret(doc, readPageContent(doc, doc.getPage(0)), IDENTITY, new Map()).images.length;
    const beforePaths = interpret(doc, readPageContent(doc, doc.getPage(0)), IDENTITY, new Map()).paths.length;
    await edit(doc, "Quarterly Report", { text: "Quarterly Repor" });
    const reread = await PDFDocument.load(await doc.save());
    const result = interpret(reread, readPageContent(reread, reread.getPage(0)), IDENTITY, new Map());
    expect(result.images.length).toBe(beforeImages);
    expect(result.paths.length).toBe(beforePaths);
  });

  it("edits Cyrillic and Greek text with the letters the document already uses", async () => {
    if (!hasFixture("chromium-multilingual.pdf")) return;
    const doc = await load("chromium-multilingual.pdf");
    const lines = linesOf(doc);
    const russian = lines.find((l) => l.text.startsWith("Русский"));
    expect(russian).toBeDefined();
    const { outcome, bytes } = await edit(doc, (russian as TextLine).text, { text: (russian as TextLine).text.replace("Съешь", "Съем") });
    expect(outcome.status).toBe("applied");
    expect(joined(await pdfjsItems(bytes))).toContain("Съем");
    const greek = linesOf(doc).find((l) => l.text.startsWith("Ελληνικά"));
    expect(greek).toBeDefined();
  });
});

describe("PDFKit (kerned and justified TJ arrays)", () => {
  it("reads justified lines as lines with word gaps", async () => {
    const doc = await load("pdfkit-standard.pdf");
    const lines = linesOf(doc);
    const justified = lines.find((l) => l.text.startsWith("The company grew"));
    expect(justified).toBeDefined();
    expect(justified?.chars.some((c) => c.gap)).toBe(true);
    expect(justified?.text).toContain("The company grew steadily");
  });

  it("keeps the word spacing of a justified line when one word changes", async () => {
    const doc = await load("pdfkit-standard.pdf");
    const line = lines0(doc, "keeping costs under control. Customer satisfaction reached an all-time high in the autumn");
    const beforeItems = await pdfjsItems(await doc.save());
    const { outcome, bytes } = await edit(doc, line.text, { text: line.text.replace("costs", "spend") });
    expect(outcome.status).toBe("applied");
    const after = await pdfjsItems(bytes);
    expect(joined(after)).toContain("keeping");
    expect(joined(after)).toContain("spend");
    // The first word has not moved.
    const first = (items: Item[]) => items.find((i) => i.str.startsWith("keeping"));
    expect(first(after)?.x).toBeCloseTo(first(beforeItems)?.x ?? Number.NaN, 2);
    const reread = linesOf(doc).find((l) => l.text.includes("spend"));
    expect(reread?.chars.filter((c) => c.gap).length).toBeGreaterThan(5);
  });

  it("edits the right-aligned line and keeps its right edge when told to", async () => {
    const doc = await load("pdfkit-standard.pdf");
    const line = lineWith(doc, "Right aligned total: 815,500");
    const rightBefore = line.origin[0] + line.advance * line.scale;
    const { outcome } = await edit(doc, "Right aligned total: 815,500", { text: "Right aligned total: 1,815,500", style: { align: "right" } });
    expect(outcome.status).toBe("applied");
    const after = lineWith(doc, "Right aligned total: 1,815,500");
    expect(after.origin[0] + after.advance * after.scale).toBeCloseTo(rightBefore, 1);
  });

  it("reads a line with a bold word in the middle as one line and moves the end of it when the bold word grows", async () => {
    const doc = await load("pdfkit-standard.pdf");
    const full = "Plain text then a bold word and the rest of the line.";
    const line = lineWith(doc, full);
    expect(line.segments.length).toBe(3);
    expect(line.joins).toEqual([null, "positioned", "positioned"]);
    const before = await pdfjsItems(await doc.save());
    const restBefore = before.find((i) => i.str.includes("and the rest"));
    const { outcome, bytes } = await edit(doc, full, { text: "Plain text then a bolder word and the rest of the line." });
    expect(outcome).toMatchObject({ status: "applied", verified: true });
    const restAfter = (await pdfjsItems(bytes)).find((i) => i.str.includes("and the rest"));
    expect(restAfter?.x).toBeGreaterThan((restBefore?.x ?? 0) + 3);
  });

  it("edits monospaced text", async () => {
    const doc = await load("pdfkit-standard.pdf");
    const { outcome, text } = await edit(doc, "Revenue   1,204,000", { text: "Revenue   2,204,000" });
    expect(outcome.status).toBe("applied");
    expect(text).toContain("2,204,000");
  });
});

function lines0(doc: PDFDocument, startsWith: string): TextLine {
  const found = linesOf(doc).find((l) => l.text.startsWith(startsWith.slice(0, 20)));
  if (!found) throw new Error(`no line starting “${startsWith}”`);
  return found;
}

describe("PDFKit with an embedded subset font", () => {
  it("edits using the embedded font's own codes where it has the letters", async () => {
    const doc = await load("pdfkit-embedded.pdf");
    const { outcome, text } = await edit(doc, "The quick brown fox jumps over the lazy dog.", { text: "The quick brown dog jumps over the lazy fox." });
    expect(outcome.status).toBe("applied");
    expect(outcome.mode).toBe("A");
    expect(text).toContain("The quick brown dog jumps over the lazy fox.");
  });

  it("falls back for a letter the subset lacks", async () => {
    const doc = await load("pdfkit-embedded.pdf");
    const { outcome, text } = await edit(doc, "The quick brown fox jumps over the lazy dog.", { text: "The quick brown fox jumps over the lazy dog!" });
    expect(outcome.status).toBe("applied");
    expect(["A", "B"]).toContain(outcome.mode);
    expect(text).toContain("lazy dog!");
  });
});

describe("pdf-lib pages", () => {
  it("edits a page that is rotated and has a CropBox, without moving the text", async () => {
    const doc = await load("pdflib-rotated.pdf");
    const line = lineWith(doc, "Lower left text");
    const { outcome } = await edit(doc, "Lower left text", { text: "Lower left words" });
    expect(outcome.status).toBe("applied");
    const after = lineWith(doc, "Lower left words");
    expect(after.origin).toEqual(line.origin);
    expect(doc.getPage(0).getRotation().angle).toBe(90);
  });

  it("edits a plain page", async () => {
    const doc = await load("pdflib-standard.pdf");
    const { text } = await edit(doc, "Hello World", { text: "Hello There" });
    expect(text).toContain("Hello There");
  });
});

describe("hand-written Type 1 with a Differences encoding and TJ kerning", () => {
  it("reads ligature glyphs as the ligature characters and lays kerned text out as one line", async () => {
    const doc = await load("kerned-type1.pdf");
    const lines = linesOf(doc);
    expect(lines[0]?.text).toBe("AVA Tea Wave");
    const second = lines[1];
    expect(second?.text).toContain("ﬁnal"); // the "fi" ligature glyph
    expect(second?.text).toContain("ﬂow"); // the "fl" ligature glyph
  });

  it("edits around a ligature without breaking it", async () => {
    const doc = await load("kerned-type1.pdf");
    const line = linesOf(doc)[1] as TextLine;
    const { outcome } = await edit(doc, line.text, { text: line.text.replace("ﬁnal", "ﬁnest") });
    expect(outcome.status).toBe("applied");
    expect(linesOf(doc).some((l) => l.text.includes("ﬁnest"))).toBe(true);
  });
});

describe("a scan has no text to edit", () => {
  it("finds no lines on an image-only page", async () => {
    const doc = await load("scan.pdf");
    expect(linesOf(doc)).toHaveLength(0);
    const result = interpret(doc, readPageContent(doc, doc.getPage(0)), IDENTITY, new Map());
    expect(result.images).toHaveLength(1);
  });
});
